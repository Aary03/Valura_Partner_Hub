/* ---------------------------------------------------------------------------
   Colour helpers. A partner can pick anything, so the band computes its own
   text colour rather than assuming the primary is dark.
   ------------------------------------------------------------------------ */
VLR.Doc.fgLum = function (hex) {
  const h = String(hex || '').replace('#', '');
  if (h.length !== 6) return 0;
  const v = i => parseInt(h.slice(i, i + 2), 16) / 255;
  const f = c => (c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));
  return 0.2126 * f(v(0)) + 0.7152 * f(v(2)) + 0.0722 * f(v(4));
};

VLR.Doc.fgVars = function (p) {
  const c1 = p.primaryHex || '#12314F';
  const c2 = p.secondaryHex || p.primaryHex || '#02A24B';
  const on = VLR.Doc.fgLum(c1) > 0.45 ? '#101614' : '#ffffff';
  return `--fg-1:${VLR.fmt.esc(c1)};--fg-2:${VLR.fmt.esc(c2)};--fg-on:${on};`;
};

/* The lockup: partner mark, then "Powered By Valura.Ai" beneath it. */
VLR.Doc.fgLockup = function (p, opts) {
  const o = opts || {};
  const d = VLR.derive(p);
  const logo = o.onInk ? (p.logoDark || p.logoLight) : (p.logoLight || p.logoDark);
  const mark = logo
    ? `<img src="${logo}" alt="${VLR.fmt.esc(d.displayName)}">`
    : VLR.fmt.esc(d.displayName);
  return `<div class="fg-lock ${o.onInk ? 'on-ink' : ''} ${o.sm ? 'sm' : ''}">
    <div class="mark">${mark}</div>
    <div class="pw">Powered By <b>Valura.Ai</b></div>
  </div>`;
};

